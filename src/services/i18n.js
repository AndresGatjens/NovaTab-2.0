export function getLang() {
  return currentLang || 'es';
}

export function setLang(lang) {
  currentLang = STRINGS[lang] ? lang : 'es';
}

export function t(key) {
  const dict = STRINGS[getLang()];
  return dict?.[key] ?? STRINGS.es[key] ?? key;
}